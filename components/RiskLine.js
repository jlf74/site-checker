// Суммарный риск штрафов. Вынесен в компонент, потому что показывается в трёх
// местах — вердикт после проверки, превью на главной, страница примера отчёта —
// и это главный аргумент сервиса: он должен выглядеть везде одинаково.
//
// Раньше сумма стояла внутри предложения и читалась как часть текста.
// Теперь подпись сверху мелкой строкой, сумма — крупной цифрой.

export default function RiskLine({ risk }) {
  if (!risk) return null;
  return (
    <div className="risk-line">
      <div className="risk-label">Суммарный риск штрафов</div>
      <div className="risk-sum">до {risk.toLocaleString('ru-RU')} ₽</div>
    </div>
  );
}
